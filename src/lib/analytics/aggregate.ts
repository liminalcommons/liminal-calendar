/**
 * Pure analytics aggregation — no DB, no clock. The route fetches recent rows
 * and passes them here with an explicit `nowMs`, so this whole module is
 * deterministic and unit-testable.
 *
 * "Recent" means the trailing window the route loads; the selected-window
 * tiles, trend and top-N lists are all derived from that same row set.
 * First-ever sightings (new vs returning) come from a separate full-history
 * query and are passed in.
 *
 * Internal traffic (admin pages, the pipeline self-test click) is collected but
 * excluded from every displayed number here — see isInternalRow.
 */

export const WINDOW_DAYS = [7, 30, 90] as const;
export type WindowDays = (typeof WINDOW_DAYS)[number];
export const DEFAULT_WINDOW_DAYS: WindowDays = 30;

/** Path prefix and click target that mark a row as internal (admin) traffic. */
export const INTERNAL_PATH_PREFIX = '/admin';
export const INTERNAL_CLICK_TARGET = 'admin:self-test';

export interface AnalyticsRow {
  type: string; // 'pageview' | 'guest_enter' | 'click'
  path: string | null;
  target: string | null;
  visitorId: string | null;
  isGuest: boolean;
  createdAt: string; // ISO 8601
  // Enrichment — null on rows recorded before these were collected, so every
  // consumer below treats null as "unknown" rather than dropping the row.
  referrerHost?: string | null;
  device?: string | null;
  country?: string | null;
  visitId?: string | null;
  viewer?: string | null;
  /** `?ref=` attribution tag; null/absent = direct or unknown. */
  ref?: string | null;
}

/** True for rows generated by admins using the dashboard, not by real guests. */
export function isInternalRow(r: Pick<AnalyticsRow, 'path' | 'target'>): boolean {
  return (
    (r.path ?? '').startsWith(INTERNAL_PATH_PREFIX) || r.target === INTERNAL_CLICK_TARGET
  );
}

export interface WindowStats {
  pageviews: number;
  uniqueVisitors: number;
  guestEntries: number;
  clicks: number;
  /** Pageviews where the guest cookie was present. */
  guestPageviews: number;
  /** Distinct visits (per-tab sessions), not raw hits. */
  visits: number;
  /** Pageviews per visit, one decimal. 0 when there are no visits. */
  pagesPerVisit: number;
  /** Visits with at least one pageview under /events/. */
  visitsToEvents: number;
  /** Visitors whose first-ever event falls inside this window. */
  newVisitors: number;
  returningVisitors: number;
}

/** A counted breakdown row, e.g. one referrer or one country. */
export interface Breakdown {
  label: string;
  count: number;
}

export interface TopPath {
  path: string;
  views: number;
}

export interface TopClick {
  target: string;
  clicks: number;
}

export interface DailyPoint {
  date: string; // YYYY-MM-DD (UTC); the bucket's first day
  /** Last day of the bucket — present on weekly buckets only. */
  endDate?: string;
  views: number;
  guestViews: number;
}

/**
 * Guest journey as plain counts (never rates). Units differ per step and the
 * panel says so: entries and RSVPs are events, event viewers are people.
 */
export interface GuestFunnel {
  /** guest_enter rows in the window. */
  guestEntries: number;
  /** Distinct guest visitors with a pageview under /events/. */
  guestEventViewers: number;
  /** rsvps created in the window with a null member_id. */
  guestRsvps: number;
  /** Members created in the window. */
  newMembers: number;
  /**
   * How `newMembers` relates to the guests above. The beacon never records a
   * member id, so there is no honest visitor→member join; this is always
   * 'window-new' (all new members, not only former guests).
   */
  newMembersBasis: 'window-new';
}

/** Counts that only the database can supply; everything else is row-derived. */
export interface FunnelDbCounts {
  guestRsvps: number;
  newMembers: number;
}

export interface AnalyticsSummary {
  /** The selected window (7/30/90 days) — drives tiles, trend and lists. */
  windowDays: WindowDays;
  window: WindowStats;
  topPaths: TopPath[];
  topClicks: TopClick[];
  /** Trend over the selected window, oldest first: daily, or weekly at 30d+. */
  dailyPageviews: DailyPoint[];
  trendBucket: 'day' | 'week';
  /** Where visitors arrived from, over the selected window. */
  topReferrers: Breakdown[];
  /** Country split (ISO alpha-2), over the selected window. */
  topCountries: Breakdown[];
  /** mobile / tablet / desktop split, over the selected window. */
  devices: Breakdown[];
  /** member / guest / anonymous split, over the selected window. */
  viewers: Breakdown[];
  /** Guest entries → event page → RSVP → new members, over the window. */
  funnel: GuestFunnel;
  /** "Brought by": distinct visitors credited per `?ref=` tag, ranked. */
  refs: Breakdown[];
  /** Distinct visitors arriving with any ref tag (refs is a capped top-N). */
  refTotal: number;
}

export interface SummaryOptions {
  windowDays?: WindowDays;
  /** DB-derived funnel steps; omitted → those steps report 0. */
  funnelDb?: FunnelDbCounts;
  /**
   * Earliest event time (epoch ms) per visitor across FULL history. When
   * omitted, falls back to the loaded rows, which can only see the loaded
   * window — so callers that care about returning visitors must pass it.
   */
  firstSeen?: Map<string, number>;
}

const DAY_MS = 24 * 60 * 60 * 1000;

function emptyWindow(): WindowStats {
  return {
    pageviews: 0, uniqueVisitors: 0, guestEntries: 0, clicks: 0, guestPageviews: 0,
    visits: 0, pagesPerVisit: 0, visitsToEvents: 0, newVisitors: 0, returningVisitors: 0,
  };
}

function statsForWindow(
  rows: AnalyticsRow[],
  sinceMs: number,
  nowMs: number,
  /** Earliest event time per visitor across full history, for new/returning. */
  firstSeen: Map<string, number>,
): WindowStats {
  const stats = emptyWindow();
  const visitors = new Set<string>();
  // visitId -> pageview count, for pages-per-visit.
  const visitPageviews = new Map<string, number>();
  const eventVisits = new Set<string>();

  for (const r of rows) {
    const t = Date.parse(r.createdAt);
    if (isNaN(t) || t < sinceMs || t > nowMs) continue;
    if (r.type === 'pageview') {
      stats.pageviews += 1;
      if (r.isGuest) stats.guestPageviews += 1;
      if (r.visitorId) visitors.add(r.visitorId);
      if (r.visitId) {
        visitPageviews.set(r.visitId, (visitPageviews.get(r.visitId) ?? 0) + 1);
        if ((r.path ?? '').startsWith('/events/')) eventVisits.add(r.visitId);
      }
    } else if (r.type === 'guest_enter') {
      stats.guestEntries += 1;
    } else if (r.type === 'click') {
      stats.clicks += 1;
    }
  }

  stats.uniqueVisitors = visitors.size;
  stats.visits = visitPageviews.size;
  stats.visitsToEvents = eventVisits.size;

  if (stats.visits > 0) {
    const viewsInVisits = Array.from(visitPageviews.values()).reduce((a, b) => a + b, 0);
    stats.pagesPerVisit = Math.round((viewsInVisits / stats.visits) * 10) / 10;
  }

  // "New" means this window contains the visitor's first-ever recorded event.
  // Computed against full history, so someone who first appeared last month
  // counts as returning today rather than new again.
  for (const id of visitors) {
    const first = firstSeen.get(id);
    if (first !== undefined && first >= sinceMs) stats.newVisitors += 1;
    else stats.returningVisitors += 1;
  }

  return stats;
}

/** Fallback first-seen map from the loaded rows only (window-limited). */
function firstSeenByVisitor(rows: AnalyticsRow[]): Map<string, number> {
  const first = new Map<string, number>();
  for (const r of rows) {
    if (!r.visitorId) continue;
    const t = Date.parse(r.createdAt);
    if (isNaN(t)) continue;
    const prev = first.get(r.visitorId);
    if (prev === undefined || t < prev) first.set(r.visitorId, t);
  }
  return first;
}

/**
 * Count a field across pageviews in the window, newest-first, capped.
 * Nulls fold into `unknownLabel` so pre-enrichment rows stay visible as
 * "unknown" instead of quietly shrinking the totals.
 */
function breakdown(
  rows: AnalyticsRow[],
  sinceMs: number,
  nowMs: number,
  pick: (r: AnalyticsRow) => string | null | undefined,
  unknownLabel: string,
  limit = 10,
): Breakdown[] {
  const counts = new Map<string, number>();
  for (const r of rows) {
    if (r.type !== 'pageview') continue;
    const t = Date.parse(r.createdAt);
    if (isNaN(t) || t < sinceMs || t > nowMs) continue;
    const raw = pick(r);
    const label = raw && raw.length > 0 ? raw : unknownLabel;
    counts.set(label, (counts.get(label) ?? 0) + 1);
  }
  return Array.from(counts.entries())
    .map(([label, count]) => ({ label, count }))
    .sort((a, b) => b.count - a.count || a.label.localeCompare(b.label))
    .slice(0, limit);
}

/** Stable identity for "a person" on a row: visitor id, else visit id. */
function personKey(r: AnalyticsRow): string | null {
  return r.visitorId ?? r.visitId ?? null;
}

/** Guest journey counts for the window. Pure; `rows` must already exclude internal traffic. */
export function computeGuestFunnel(
  rows: AnalyticsRow[],
  sinceMs: number,
  nowMs: number,
  db: FunnelDbCounts = { guestRsvps: 0, newMembers: 0 },
): GuestFunnel {
  let guestEntries = 0;
  const eventViewers = new Set<string>();
  for (const r of rows) {
    const t = Date.parse(r.createdAt);
    if (isNaN(t) || t < sinceMs || t > nowMs) continue;
    if (r.type === 'guest_enter') {
      guestEntries += 1;
    } else if (r.type === 'pageview' && r.isGuest && (r.path ?? '').startsWith('/events/')) {
      const key = personKey(r);
      if (key) eventViewers.add(key);
    }
  }
  return {
    guestEntries,
    guestEventViewers: eventViewers.size,
    guestRsvps: db.guestRsvps,
    newMembers: db.newMembers,
    newMembersBasis: 'window-new',
  };
}

/**
 * Credit `?ref=` tags: each distinct visitor counts once per tag, however many
 * pages they viewed. Rows without a tag are direct/unknown and not listed.
 */
export function computeRefs(
  rows: AnalyticsRow[],
  sinceMs: number,
  nowMs: number,
  limit = 10,
): { refs: Breakdown[]; total: number } {
  const byRef = new Map<string, Set<string>>();
  const credited = new Set<string>();
  let anonymous = 0; // tagged rows with no id at all — each counts once
  const anonByRef = new Map<string, number>();
  for (const r of rows) {
    if (r.type !== 'pageview' || !r.ref) continue;
    const t = Date.parse(r.createdAt);
    if (isNaN(t) || t < sinceMs || t > nowMs) continue;
    const key = personKey(r);
    if (key) {
      if (!byRef.has(r.ref)) byRef.set(r.ref, new Set());
      byRef.get(r.ref)!.add(key);
      credited.add(key);
    } else {
      anonByRef.set(r.ref, (anonByRef.get(r.ref) ?? 0) + 1);
      anonymous += 1;
    }
  }
  const labels = new Set([...byRef.keys(), ...anonByRef.keys()]);
  const refs = Array.from(labels)
    .map((label) => ({ label, count: (byRef.get(label)?.size ?? 0) + (anonByRef.get(label) ?? 0) }))
    .sort((a, b) => b.count - a.count || a.label.localeCompare(b.label));
  return { refs: refs.slice(0, limit), total: credited.size + anonymous };
}

function utcDateKey(ms: number): string {
  return new Date(ms).toISOString().slice(0, 10);
}

/** Trend buckets: one per day for short windows, rolling 7-day buckets at 30d+. */
function buildTrend(
  rows: AnalyticsRow[],
  nowMs: number,
  windowDays: WindowDays,
): { points: DailyPoint[]; bucket: 'day' | 'week' } {
  const sinceMs = nowMs - windowDays * DAY_MS;
  const views = rows.filter((r) => {
    if (r.type !== 'pageview') return false;
    const t = Date.parse(r.createdAt);
    return !isNaN(t) && t >= sinceMs && t <= nowMs;
  });

  if (windowDays < 30) {
    // Seeded with every calendar day so gaps render as zeroes.
    const daily = new Map<string, DailyPoint>();
    for (let i = windowDays - 1; i >= 0; i--) {
      const key = utcDateKey(nowMs - i * DAY_MS);
      daily.set(key, { date: key, views: 0, guestViews: 0 });
    }
    for (const r of views) {
      const point = daily.get(utcDateKey(Date.parse(r.createdAt)));
      if (!point) continue;
      point.views += 1;
      if (r.isGuest) point.guestViews += 1;
    }
    return { points: Array.from(daily.values()), bucket: 'day' };
  }

  // Bucket 0 is the newest 7 days; the oldest bucket is clipped to the window.
  const count = Math.ceil(windowDays / 7);
  const weeks: DailyPoint[] = [];
  for (let i = count - 1; i >= 0; i--) {
    const start = Math.max(sinceMs, nowMs - (i + 1) * 7 * DAY_MS);
    const end = nowMs - i * 7 * DAY_MS;
    weeks.push({ date: utcDateKey(start), endDate: utcDateKey(end), views: 0, guestViews: 0 });
  }
  for (const r of views) {
    const age = Math.floor((nowMs - Date.parse(r.createdAt)) / (7 * DAY_MS));
    const point = weeks[count - 1 - Math.min(count - 1, age)];
    point.views += 1;
    if (r.isGuest) point.guestViews += 1;
  }
  return { points: weeks, bucket: 'week' };
}

/**
 * Aggregate recent rows into the admin dashboard summary. `nowMs` is the
 * reference "now" (epoch millis) used to slice the trailing windows.
 */
export function computeAnalyticsSummary(
  allRows: AnalyticsRow[],
  nowMs: number,
  opts: SummaryOptions = {},
): AnalyticsSummary {
  const windowDays = opts.windowDays ?? DEFAULT_WINDOW_DAYS;
  const windowStart = nowMs - windowDays * DAY_MS;

  // Internal traffic is collected but never displayed.
  const rows = allRows.filter((r) => !isInternalRow(r));

  // Top paths / clicks over the selected window.
  const pathCounts = new Map<string, number>();
  const clickCounts = new Map<string, number>();

  for (const r of rows) {
    const t = Date.parse(r.createdAt);
    if (isNaN(t) || t < windowStart || t > nowMs) continue;
    if (r.type === 'pageview') {
      const p = r.path && r.path.length > 0 ? r.path : '(unknown)';
      pathCounts.set(p, (pathCounts.get(p) ?? 0) + 1);
    } else if (r.type === 'click') {
      const target = r.target && r.target.length > 0 ? r.target : '(unlabeled)';
      clickCounts.set(target, (clickCounts.get(target) ?? 0) + 1);
    }
  }

  const topPaths: TopPath[] = Array.from(pathCounts.entries())
    .map(([path, views]) => ({ path, views }))
    .sort((a, b) => b.views - a.views || a.path.localeCompare(b.path))
    .slice(0, 10);

  const topClicks: TopClick[] = Array.from(clickCounts.entries())
    .map(([target, clicks]) => ({ target, clicks }))
    .sort((a, b) => b.clicks - a.clicks || a.target.localeCompare(b.target))
    .slice(0, 10);

  const firstSeen = opts.firstSeen ?? firstSeenByVisitor(rows);
  const trend = buildTrend(rows, nowMs, windowDays);
  const refResult = computeRefs(rows, windowStart, nowMs);

  return {
    funnel: computeGuestFunnel(rows, windowStart, nowMs, opts.funnelDb),
    refs: refResult.refs,
    refTotal: refResult.total,
    windowDays,
    window: statsForWindow(rows, windowStart, nowMs, firstSeen),
    topPaths,
    topClicks,
    dailyPageviews: trend.points,
    trendBucket: trend.bucket,
    topReferrers: breakdown(rows, windowStart, nowMs, (r) => r.referrerHost, '(unknown)'),
    topCountries: breakdown(rows, windowStart, nowMs, (r) => r.country, '(unknown)'),
    devices: breakdown(rows, windowStart, nowMs, (r) => r.device, '(unknown)', 4),
    viewers: breakdown(rows, windowStart, nowMs, (r) => r.viewer, '(unknown)', 4),
  };
}

